#!/usr/bin/env node
// Single source (src/) → per-tool outputs in plugins/dominicode-job-hunt/.
//
//   node scripts/build.mjs           write outputs
//   node scripts/build.mjs --check   fail if committed outputs differ from a fresh build
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { join, dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml } from 'yaml';
import { parse as parseToml } from 'smol-toml';
import { loadPatterns, scanPaths, scanText, formatFindings } from './check-leaks.mjs';

export const PLUGIN_DIR = 'plugins/dominicode-job-hunt';
const SKILL_NAME = 'job-hunt';

const toPosix = (p) => p.split(sep).join('/');

function listFiles(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (name === '.gitkeep') return [];
    return statSync(full).isDirectory() ? listFiles(full) : [full];
  });
}

function splitFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) return { frontmatter: null, body: raw };
  return { frontmatter: match[1], body: match[2] };
}

export class BuildError extends Error {}

/**
 * Strict YAML frontmatter (some hosts drop a skill silently on a lax parse error,
 * e.g. an unquoted description containing ": "). Errors carry `file:line`,
 * where line 1 is the opening `---`.
 */
function readMeta(raw, file, required) {
  const { frontmatter, body } = splitFrontmatter(raw);
  if (frontmatter === null) throw new BuildError(`${file}:1 missing YAML frontmatter`);
  let meta;
  try {
    meta = parseYaml(frontmatter, { strict: true, uniqueKeys: true, prettyErrors: true });
  } catch (err) {
    const line = (err.linePos?.[0]?.line ?? 0) + 1;
    throw new BuildError(`${file}:${line} invalid YAML frontmatter: ${err.message.split('\n')[0]}`);
  }
  if (!meta || typeof meta !== 'object') throw new BuildError(`${file}:2 frontmatter must be a mapping`);
  for (const key of required) {
    if (typeof meta[key] !== 'string' || !meta[key].trim()) {
      throw new BuildError(`${file}:1 frontmatter is missing "${key}"`);
    }
  }
  return { meta, body };
}

function tomlString(value) {
  if (!value.includes("'''")) return `'''\n${value}'''`;
  const escaped = value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r/g, '\\r').replace(/\n/g, '\\n').replace(/\t/g, '\\t');
  return `"${escaped}"`;
}

const basicString = (value) => JSON.stringify(value);

/**
 * Neutral tool names used in src/agents → Claude Code tool names.
 * `browser` has no fixed Claude name (it depends on the browser MCP the user
 * connected), so an agent that needs it omits `tools` and inherits everything.
 */
const CLAUDE_TOOLS = {
  read: ['Read'],
  write: ['Write'],
  edit: ['Edit'],
  search: ['Glob', 'Grep'],
  shell: ['Bash'],
  web: ['WebSearch', 'WebFetch'],
  browser: null,
};

function claudeAgent(agent) {
  const lines = ['---', `name: ${agent.meta.name}`, `description: ${basicString(agent.meta.description)}`];
  const tools = agent.meta.tools ?? [];
  if (!tools.includes('browser') && tools.length) {
    lines.push(`tools: ${[...new Set(tools.flatMap((t) => CLAUDE_TOOLS[t]))].join(', ')}`);
  }
  lines.push('---', '', '');
  return lines.join('\n') + agent.instructions;
}

const demote = (markdown, levels) =>
  markdown.replace(/^(#{1,6}) /gm, (_, hashes) => '#'.repeat(Math.min(6, hashes.length + levels)) + ' ');

function fence(content, lang = 'markdown') {
  const longest = Math.max(2, ...(content.match(/`{3,}/g) ?? []).map((m) => m.length));
  const ticks = '`'.repeat(longest + 1);
  return `${ticks}${lang}\n${content.endsWith('\n') ? content : content + '\n'}${ticks}`;
}

/** One self-contained file for tools that read AGENTS.md (Cursor, Gemini CLI, Aider…). */
function agentsMirror({ skillBody, agents, references, templates }) {
  const parts = [
    '<!-- Generated by scripts/build.mjs from src/ — do not edit. -->',
    '',
    '> **How to read this file.** This is the job-hunt skill for tools that read `AGENTS.md`, with every file it refers to inlined below.',
    '> `<skill>/references/job-*.md` → the matching **Role** section · other `<skill>/references/*.md` → **References** · `<skill>/templates/…` → **Templates**.',
    '> The scripts (`<skill>/scripts/export-cv.mjs`, Node 20+) are not inlined: they live in `plugins/dominicode-job-hunt/skills/job-hunt/scripts/` of the package repository. If you cloned it, `<skill>` is that `skills/job-hunt` folder. Without the scripts, keep the CV in Markdown and skip the export step.',
    '',
    skillBody.trim(),
    '',
    '---',
    '',
    '# Roles',
    '',
    'When this file says to launch a `job-*` agent, do that role yourself with the instructions below.',
  ];
  for (const agent of agents) {
    parts.push('', `## Role: ${agent.meta.name}`, '', `> ${agent.meta.description}`, '', demote(agent.instructions.trim(), 2));
  }
  if (references.length) {
    parts.push('', '---', '', '# References');
    for (const ref of references) parts.push('', `## ${ref.path}`, '', demote(ref.content.trim(), 2));
  }
  if (templates.length) {
    parts.push('', '---', '', '# Templates', '', 'Create these files when the user runs `init`.');
    for (const tpl of templates) parts.push('', `## \`${tpl.path}\``, '', fence(tpl.content));
  }
  return parts.join('\n') + '\n';
}

function loadAgents(root, srcDir) {
  const agentsDir = join(srcDir, 'agents');
  if (!existsSync(agentsDir)) return [];
  return listFiles(agentsDir)
    .filter((f) => f.endsWith('.md'))
    .sort()
    .map((file) => {
      const rel = toPosix(relative(root, file));
      const { meta, body } = readMeta(readFileSync(file, 'utf8'), rel, ['name', 'description']);
      if (meta.tools !== undefined && !Array.isArray(meta.tools)) {
        throw new BuildError(`${rel}:1 "tools" must be a list`);
      }
      for (const tool of meta.tools ?? []) {
        if (!(tool in CLAUDE_TOOLS)) {
          throw new BuildError(`${rel}:1 unknown tool "${tool}" (allowed: ${Object.keys(CLAUDE_TOOLS).join(', ')})`);
        }
      }
      let instructions = body.trim() + '\n';
      if (meta.instructions) {
        const path = join(srcDir, 'skill', meta.instructions);
        if (!existsSync(path)) throw new BuildError(`${rel}:1 instructions file not found: ${meta.instructions}`);
        instructions = readFileSync(path, 'utf8');
      }
      return { file: rel, meta, instructions };
    });
}

function loadSkill(root, srcDir) {
  const file = join(srcDir, 'skill', 'SKILL.md');
  const rel = toPosix(relative(root, file));
  if (!existsSync(file)) throw new BuildError(`${rel}: not found`);
  return readMeta(readFileSync(file, 'utf8'), rel, ['name', 'description']);
}

const SKILL_OUT = `${PLUGIN_DIR}/skills/${SKILL_NAME}`;

/** Reads and validates everything under src/. */
function loadSource(root) {
  const srcDir = join(root, 'src');
  const skill = loadSkill(root, srcDir);
  const agents = loadAgents(root, srcDir);
  const roleFiles = new Set(agents.map((a) => a.meta.instructions).filter(Boolean));
  const skillFiles = listFiles(join(srcDir, 'skill')).map((file) => ({
    path: toPosix(relative(join(srcDir, 'skill'), file)),
    content: readFileSync(file, 'utf8'),
  }));
  return {
    skill,
    agents,
    skillFiles,
    references: skillFiles.filter((f) => f.path.startsWith('references/') && !roleFiles.has(f.path)),
    templates: skillFiles.filter((f) => f.path.startsWith('templates/')),
  };
}

const manifestBase = (pkg) => ({
  name: pkg.name,
  version: pkg.version,
  description: pkg.description,
  author: { name: pkg.author },
  license: pkg.license,
});

const json = (value) => JSON.stringify(value, null, 2) + '\n';

function codexToml(agent) {
  const toml = [
    `# Generated by scripts/build.mjs from src/agents/${agent.meta.name}.md — do not edit.`,
    `name = ${basicString(agent.meta.name)}`,
    `description = ${basicString(agent.meta.description)}`,
    `developer_instructions = ${tomlString(agent.instructions)}`,
    '',
  ].join('\n');
  try {
    parseToml(toml);
  } catch (err) {
    throw new BuildError(`${agent.file}: generated TOML does not parse: ${err.message.split('\n')[0]}`);
  }
  return toml;
}

/** Codex: the skill (shared with Claude Code), agents as TOML inside it, and the manifest. */
function emitCodex(source, pkg) {
  return [
    ...source.skillFiles.map((f) => [`${SKILL_OUT}/${f.path}`, f.content]),
    ...source.agents.map((a) => [`${SKILL_OUT}/codex-agents/${a.meta.name}.toml`, codexToml(a)]),
    [`${PLUGIN_DIR}/.codex-plugin/plugin.json`, json({ ...manifestBase(pkg), skills: './skills/' })],
  ];
}

/** Claude Code: agents as Markdown and the manifest (skills/ is discovered by convention). */
function emitClaude(source, pkg) {
  return [
    ...source.agents.map((a) => [`${PLUGIN_DIR}/agents/${a.meta.name}.md`, claudeAgent(a)]),
    [`${PLUGIN_DIR}/.claude-plugin/plugin.json`, json(manifestBase(pkg))],
  ];
}

/** Everything else: one self-contained AGENTS.md. */
function emitMirror(source) {
  const { skill, agents, references, templates } = source;
  return [[`${PLUGIN_DIR}/AGENTS.md`, agentsMirror({ skillBody: skill.body, agents, references, templates })]];
}

/** Returns Map(relative posix path → content) of every generated file. */
export function generate({ root, pkg }) {
  const source = loadSource(root);
  return new Map([...emitCodex(source, pkg), ...emitClaude(source, pkg), ...emitMirror(source)]);
}

/** Leaks in the source tree and in every generated file (manifest credits are allowed). */
function assertNoLeaks(root, files, patterns) {
  const relativize = (f) => ({ ...f, file: toPosix(relative(root, f.file)) });
  // Everything users see: the source, the public docs and manifests at the root, and the outputs.
  const shipped = ['src', 'README.md', 'README.es.md', 'AGENTS.md', '.agents', '.claude-plugin', 'specs']
    .map((p) => join(root, p))
    .filter((p) => existsSync(p));
  const findings = [
    ...scanPaths(shipped, { patterns }).map(relativize),
    ...[...files].flatMap(([path, content]) => scanText(content, { file: path, patterns })),
  ];
  if (findings.length) {
    throw new BuildError(`${findings.length} leak(s) found, nothing was written:\n${formatFindings(findings)}`);
  }
}

/** Differences between a fresh build and what is on disk under PLUGIN_DIR. */
function diffAgainstDisk(root, files) {
  const pluginRoot = join(root, PLUGIN_DIR);
  const onDisk = existsSync(pluginRoot)
    ? listFiles(pluginRoot).map((f) => toPosix(relative(root, f)))
    : [];
  const drift = [];
  for (const [path, content] of files) {
    const full = join(root, path);
    if (!existsSync(full)) drift.push(`missing: ${path}`);
    else if (readFileSync(full, 'utf8') !== content) drift.push(`modified: ${path}`);
  }
  for (const path of onDisk) if (!files.has(path)) drift.push(`extra: ${path}`);
  return drift.sort();
}

export function build({ root, pkg, check = false, patterns = loadPatterns() }) {
  const files = generate({ root, pkg });
  assertNoLeaks(root, files, patterns);
  if (check) {
    const drift = diffAgainstDisk(root, files);
    if (drift.length) {
      throw new BuildError(`${PLUGIN_DIR} is out of sync with src/ — run \`npm run build\`:\n${drift.join('\n')}`);
    }
    return { files, drift };
  }
  rmSync(join(root, PLUGIN_DIR), { recursive: true, force: true });
  for (const [path, content] of files) {
    const full = join(root, path);
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, content);
  }
  return { files };
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  try {
    const check = process.argv.includes('--check');
    const { files } = build({ root, pkg, check });
    console.log(check ? `${PLUGIN_DIR} is in sync (${files.size} files).` : `Built ${files.size} file(s) into ${PLUGIN_DIR}.`);
  } catch (err) {
    if (!(err instanceof BuildError)) throw err;
    console.error(`Build failed:\n${err.message}`);
    process.exit(1);
  }
}

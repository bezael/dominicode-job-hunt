#!/usr/bin/env node
// Installs the job-hunt agents for Codex. Codex plugins cannot bundle custom
// agents yet, so the TOML files ship inside this skill and are copied here.
//
//   node install-codex-agents.mjs              → $CODEX_HOME/agents (default ~/.codex/agents)
//   node install-codex-agents.mjs --project    → ./.codex/agents (Codex loads it only in trusted projects)
//   options: --force (overwrite files that differ) · --source <dir> · --target <dir>
//
// Files written by an earlier version of this package are updated in place; any other
// file with the same name is left alone unless --force is given.
//
// No dependencies: Node built-ins only.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync, realpathSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const DEFAULT_SOURCE = join(HERE, '..', 'codex-agents');
/** First line of every agent file this package generates. */
export const GENERATED_MARK = '# Generated by scripts/build.mjs';

export function defaultTarget({ project = false, env = process.env, cwd = process.cwd() } = {}) {
  if (project) return join(cwd, '.codex', 'agents');
  return join(env.CODEX_HOME || join(homedir(), '.codex'), 'agents');
}

/** Copies every .toml from `source` to `target`. Returns { copied, updated, skipped, identical }. */
export function installAgents({ source = DEFAULT_SOURCE, target, force = false }) {
  if (!existsSync(source)) throw new Error(`Agent folder not found: ${source}`);
  const files = readdirSync(source).filter((name) => name.endsWith('.toml')).sort();
  if (files.length === 0) throw new Error(`No .toml agents in ${source}`);
  mkdirSync(target, { recursive: true });
  const result = { copied: [], updated: [], skipped: [], identical: [] };
  for (const name of files) {
    const incoming = readFileSync(join(source, name));
    const destination = join(target, name);
    if (existsSync(destination)) {
      const current = readFileSync(destination);
      if (current.equals(incoming)) {
        result.identical.push(name);
        continue;
      }
      const ours = current.toString('utf8').startsWith(GENERATED_MARK);
      if (!ours && !force) {
        result.skipped.push(name);
        continue;
      }
      writeFileSync(destination, incoming);
      result.updated.push(name);
      continue;
    }
    writeFileSync(destination, incoming);
    result.copied.push(name);
  }
  return result;
}

/** The `[projects.…]` key Codex expects for a folder: lowercase on Windows only, as a TOML basic string. */
export function trustKey(cwd = process.cwd(), platform = process.platform) {
  return `[projects.${JSON.stringify(platform === 'win32' ? cwd.toLowerCase() : cwd)}]`;
}

function parseArgs(argv) {
  const args = { project: false, force: false, source: DEFAULT_SOURCE, target: null };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--project') args.project = true;
    else if (arg === '--force') args.force = true;
    else if (arg === '--source') args.source = resolve(argv[++i]);
    else if (arg === '--target') args.target = resolve(argv[++i]);
    else throw new Error(`Unknown option: ${arg}`);
  }
  return args;
}

const same = (a, b) => (process.platform === 'win32' ? a.toLowerCase() === b.toLowerCase() : a === b);
// realpath on both sides: the skill may be reached through a symlink or a junction.
const isMain = (() => {
  try {
    return Boolean(process.argv[1]) && same(realpathSync(process.argv[1]), realpathSync(fileURLToPath(import.meta.url)));
  } catch {
    return false;
  }
})();

if (isMain) {
  try {
    const args = parseArgs(process.argv.slice(2));
    const target = args.target ?? defaultTarget({ project: args.project });
    const { copied, updated, skipped, identical } = installAgents({ source: args.source, target, force: args.force });
    console.log(`Codex agents → ${target}`);
    if (copied.length) console.log(`  copied:    ${copied.join(', ')}`);
    if (updated.length) console.log(`  updated:   ${updated.join(', ')}`);
    if (identical.length) console.log(`  identical: ${identical.join(', ')}`);
    if (skipped.length) {
      console.log(`  skipped (a different file already exists): ${skipped.join(', ')}`);
      console.log('  Re-run with --force to overwrite them.');
    }
    if (args.project && !args.target) {
      console.log('');
      console.log('Note: Codex only loads .codex/agents from TRUSTED projects. If this folder is not');
      console.log('trusted yet, add this to ~/.codex/config.toml (exact path of this folder):');
      console.log(`  ${trustKey()}`);
      console.log('  trust_level = "trusted"');
      console.log('Or install globally instead: run this script again without --project.');
    }
    console.log('Restart Codex to load new agents.');
    if (skipped.length) process.exitCode = 2;
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
